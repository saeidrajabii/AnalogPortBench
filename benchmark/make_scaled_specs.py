#!/usr/bin/env python3
"""Write circuits/<c>/spec_1v2.yaml: the spec for a port at VDD = 1.2 V with voltage-range limits scaled to the supply.

  python benchmark/make_scaled_specs.py

spec.yaml is derived from the 180 nm design at 1.8 V. Limits that measure a voltage RANGE (output swing, matched
output range of a bias circuit) cannot be held at a lower supply: e.g. cascode_bias_ws asks for a 1.144 V matched
range, which no design reaches at VDD = 1.2 V (each rail needs ~80 mV, so ~1.04 V is the physical limit).
In spec_1v2.yaml those limits are multiplied by 1.2 / 1.8; every other limit is copied unchanged.
spec.yaml evaluated at 1.2 V remains available as the deliberately infeasible variant of the task.
"""
import yaml

import config

SCALED = {"match_width_V", "swing_V"}       # voltage-range metrics that scale with the supply
VDD_SRC, VDD = 1.8, 1.2


def main():
    for spec in sorted(config.BENCH.glob("circuits/*/spec.yaml")):
        s = yaml.safe_load(spec.read_text())
        if not SCALED & set(s["limits"]):
            continue
        for k in SCALED & set(s["limits"]):
            r = s["limits"][k]
            r["limit"] = round(r["limit"] * VDD / VDD_SRC, 4)
            r["rule"] = f"{r['rule']}, scaled by VDD ratio {VDD:g}/{VDD_SRC:g}"
        s["vdd"] = VDD
        s["conditions"] = s.get("conditions", "").replace("VDD = 1.8 V (source)", f"VDD = {VDD:g} V (port)")
        out = spec.with_name("spec_1v2.yaml")
        out.write_text("# Generated by benchmark/make_scaled_specs.py: spec.yaml with voltage-range limits scaled to "
                       "VDD = 1.2 V.\n" + yaml.safe_dump(s, sort_keys=False))
        print(f"wrote {out.relative_to(config.REPO)}: " + ", ".join(
            f"{k} >= {s['limits'][k]['limit']}" for k in SCALED & set(s["limits"])))


if __name__ == "__main__":
    main()
