#!/usr/bin/env python3
"""Step 5: "naive port" baseline. Swap 180 nm devices for Sky130 LVT ones and change nothing else.

  python benchmark/naive_port.py [--vdd 1.8 1.5 1.2]

For every circuit's source_180n.sp it writes two ported netlists to circuits/<name>/ported/:
  sky130_naive_keepL.sp    W unchanged,           L = max(L, Lmin)
  sky130_naive_scaledL.sp  W, L x (150/180),       L = max(L, Lmin)   (rounded to a 5 nm grid)
with Lmin = 0.15 um (nfet_01v8_lvt) and 0.35 um (pfet_01v8_lvt). Topology, multipliers (m),
bulk connections, R, C, Iref, VCM and the load stay exactly as in the source.

Each ported netlist is then evaluated against the circuit's spec at every VDD given (default
1.8, 1.5 and 1.2 V; testbench bias such as VCM is NOT adjusted for the lower supplies).
Report: build/naive_port/report.md and report.json.
"""
import argparse
import json
import re

import config
from circuits import CIRCUITS
from evaluate import evaluate, print_result
from netlist import mos_type
from techs import TECHS

SKY = TECHS["sky130_lvt"]
SCALE = 150 / 180
SUFFIX = {"f": 1e-15, "p": 1e-12, "n": 1e-9, "u": 1e-6, "m": 1e-3, "k": 1e3, "meg": 1e6, "g": 1e9}
MOS_180N = re.compile(r"^(\s*)(M\S+)\s+(\S+)\s+(\S+)\s+(\S+)\s+(\S+)\s+(tsmc18d[NP])\s+(.*)$", re.I)


def spice_num(s):
    m = re.match(r"^([-+]?[\d.]+(?:e[-+]?\d+)?)(meg|[fpnumkg])?", s.strip().lower())
    return float(m.group(1)) * SUFFIX.get(m.group(2), 1.0)


def grid(x, step=0.005):
    return round(round(x / step) * step, 3)


def port_line(line, variant, log):
    m = MOS_180N.match(line)
    if not m:
        return line
    indent, name, d, g, s, b, model, rest = m.groups()
    p = {k.lower(): v for k, v in re.findall(r"(\w+)=(\S+)", rest)}
    typ = mos_type(model)
    w, l = spice_num(p["w"]) * 1e6, spice_num(p["l"]) * 1e6          # in um
    mult = spice_num(p.get("m", "1"))
    if variant == "scaledL":
        w, l = grid(w * SCALE), grid(l * SCALE)
    l_new = max(l, SKY["lmin"][typ])
    log.append(f"{name}: {model} W={spice_num(p['w'])*1e6:g} L={spice_num(p['l'])*1e6:g} -> "
               f"{typ}fet_01v8_lvt W={w:g} L={l_new:g}{' (clamped to Lmin)' if l_new != l else ''} m={mult:g}")
    return indent + SKY["line"](name, d, g, s, b, typ, w, l_new, mult)


def port(circuit, variant):
    src = config.BENCH / "circuits" / circuit / "source_180n.sp"
    log, body = [], []
    for line in src.read_text().splitlines():
        if line.startswith("* Technology:"):
            continue
        body.append(port_line(line, variant, log))
    head = [f"* {circuit}: NAIVE PORT ({variant}) of source_180n.sp to Sky130 1.8 V LVT devices.",
            "* Generated by benchmark/naive_port.py: device swap + length rule only; topology, m, bulks,",
            "* R/C values unchanged. Sizes in um (Sky130 models use .option scale=1u).",
            "* Device changes:"] + [f"*   {x}" for x in log]
    out = config.BENCH / "circuits" / circuit / "ported" / f"sky130_naive_{variant}.sp"
    out.parent.mkdir(exist_ok=True)
    out.write_text("\n".join(head + body) + "\n")
    return out


def fmt(v):
    return f"{v:.4g}" if isinstance(v, (int, float)) and not isinstance(v, bool) else str(v)


def report(results, vdds):
    lines = ["# Naive port baseline: TSMC 0.18 um -> Sky130 1.8 V LVT", "",
             "Device swap only (see `benchmark/naive_port.py`). TT corner, 27 C. Testbench bias (Iref, VCM, CL) "
             "unchanged at every VDD. `keepL`: W, L unchanged (L clamped to Lmin). `scaledL`: W, L x 150/180, "
             "then clamped. Mirror and cascode-bias outputs are held by a voltage source, so for those "
             "circuits VDD only changes the supply of the bias branches.", ""]
    lines += ["## Summary (overall PASS/FAIL)", "",
              "| circuit | variant | " + " | ".join(f"VDD={v:g} V" for v in vdds) + " |",
              "|---|---|" + "---|" * len(vdds)]
    for (c, var), byv in results.items():
        cells = []
        for v in vdds:
            r = byv[v]
            fails = [x["metric"] for x in r.get("checks", []) if not x["pass"]]
            cells.append("ERROR" if r["errors"] else ("PASS" if r.get("pass") else "FAIL: " + ", ".join(fails)))
        lines.append(f"| {c} | {var} | " + " | ".join(cells) + " |")
    lines += ["", "## Details", ""]
    for (c, var), byv in results.items():
        r0 = byv[vdds[0]]
        lines += [f"### {c} / {var}", "", "| metric | 180 nm | limit | " +
                  " | ".join(f"{v:g} V" for v in vdds) + " |", "|---|---|---|" + "---|" * len(vdds)]
        for chk in r0.get("checks", []):
            m = chk["metric"]
            vals = []
            for v in vdds:
                cc = next((x for x in byv[v].get("checks", []) if x["metric"] == m), None)
                vals.append(f"{fmt(cc['value'])} {'✓' if cc and cc['pass'] else '✗'}" if cc else "-")
            lines.append(f"| {m} | {fmt(chk['source'])} | {chk['op']} {fmt(chk['limit'])} | " + " | ".join(vals) + " |")
        for v in vdds:
            r = byv[v]
            if "headroom" in r and r["headroom"]["triode_devices"]:
                lines.append(f"\nTriode at {v:g} V: " + ", ".join(
                    f"`{d['device']}` (Vds={d['vds_V']}, Vdsat={d['vdsat_V']})"
                    for d in r["headroom"]["devices"] if d["margin_V"] < 0))
            for e in r["errors"]:
                lines.append(f"\nError at {v:g} V: `{e[:300]}`")
        if r0["warnings"]:
            lines += [""] + [f"- warning: {w}" for w in r0["warnings"]]
        lines.append("")
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--vdd", type=float, nargs="+", default=[1.8, 1.5, 1.2])
    a = ap.parse_args()
    results = {}
    for c in CIRCUITS:
        for var in ("keepL", "scaledL"):
            net = port(c, var)
            for v in a.vdd:
                r = evaluate(c, net, "sky130_lvt", v, label=f"naive_{var}_{v:g}V")
                print_result(r)
                results.setdefault((c, var), {})[v] = r
    out = config.BUILD / "naive_port"
    out.mkdir(parents=True, exist_ok=True)
    (out / "report.md").write_text(report(results, a.vdd))
    (out / "report.json").write_text(json.dumps({f"{c}/{var}": {str(v): r for v, r in byv.items()}
                                                  for (c, var), byv in results.items()}, indent=2))
    print(f"\nreport: {out / 'report.md'}")


if __name__ == "__main__":
    main()
