#!/usr/bin/env python3
"""Derive each circuit's spec.yaml from a simulation of its 180 nm source design.

  python benchmark/make_specs.py [circuit ...]       (needs TSMC018_LIB; default: all circuits)

The limit rules below are the editable part: a port "meets spec" when it is roughly as good as the
180 nm original. Metrics without a rule are recorded in spec.yaml for reference only.
"""
import sys

import yaml

import config
from circuits import CIRCUITS
from evaluate import evaluate

# metric: (comparison, function of the 180 nm value -> limit, human-readable rule)
RULES = {
    "iout_err_pct":   ("abs<=", lambda s: 10.0,           "|Iout - Iref| <= 10 % at Vo = 0.9 V"),
    "rout_kohm":      (">=",    lambda s: 0.5 * s,        ">= 0.5 x source"),
    "vmin_V":         ("<=",    lambda s: s + 0.1,        "<= source + 0.1 V"),
    "mismatch_0v9_nA": ("abs<=", lambda s: 1000.0,        "|mismatch| <= 1 uA at Vo = 0.9 V"),
    "match_width_V":  (">=",    lambda s: 0.8 * s,        ">= 0.8 x source"),
    "isink_err_pct":  ("abs<=", lambda s: 10.0,           "|Isink - Iref| <= 10 % at Vo = 0.9 V"),
    "isource_err_pct": ("abs<=", lambda s: 10.0,          "|Isource - Iref| <= 10 % at Vo = 0.9 V"),
    "dc_gain_dB":     (">=",    lambda s: s - 3,          ">= source - 3 dB"),
    "ugb_Hz":         (">=",    lambda s: 0.8 * s,        ">= 0.8 x source"),
    "ugf_Hz":         (">=",    lambda s: 0.8 * s,        ">= 0.8 x source"),
    "pm_deg":         (">=",    lambda s: 55.0,           ">= 55 deg"),
    "gm_dB":          (">=",    lambda s: 10.0,           ">= 10 dB"),
    "power_uW":       ("<=",    lambda s: 1.2 * s,        "<= 1.2 x source"),
    "rise_settle_ns": ("<=",    lambda s: 1.5 * s,        "<= 1.5 x source"),
    "fall_settle_ns": ("<=",    lambda s: 1.5 * s,        "<= 1.5 x source"),
    "swing_V":        (">=",    lambda s: 0.8 * s,        ">= 0.8 x source"),
    "n_triode":       ("<=",    lambda s: s,              "no more transistors out of saturation than the source"),
}


def sig(x):
    return float(f"{x:.4g}") if isinstance(x, float) else x


def main(names=None):
    for name, cfg in CIRCUITS.items():
        if names and name not in names:
            continue
        src = config.BENCH / "circuits" / name / "source_180n.sp"
        r = evaluate(name, src, tech="tsmc018", label="source")
        if r["errors"]:
            sys.exit(f"{name}: source simulation failed: {r['errors']}")
        m = r["metrics"]
        spec = {
            "circuit": name,
            "description": cfg["description"],
            "dut_ports": cfg["ports"],
            "testbenches": cfg["testbenches"],
            "conditions": "TT, 27 C, VDD = 1.8 V (source), Iref = 20 uA",
            "limits": {k: {"op": RULES[k][0], "limit": sig(RULES[k][1](v)), "source": sig(v), "rule": RULES[k][2]}
                       for k, v in m.items() if k in RULES and v is not None},
            "reference_only": {k: sig(v) for k, v in m.items() if k not in RULES},
            "source_triode_devices": r["headroom"]["triode_devices"],
        }
        out = config.BENCH / "circuits" / name / "spec.yaml"
        out.write_text("# Generated by benchmark/make_specs.py from the 180 nm source design; edit RULES there.\n"
                       + yaml.safe_dump(spec, sort_keys=False))
        print(f"wrote {out.relative_to(config.REPO)}")


if __name__ == "__main__":
    main(sys.argv[1:])          # optional: circuit names (default: all)
